import { writeFile } from "node:fs/promises";

const overpassUrl = process.env.OVERPASS_URL || "https://overpass-api.de/api/interpreter";
const outputPath = new URL("./open-data.mjs", import.meta.url);

const query = `
[out:json][timeout:180];
(
  nwr["craft"="winery"](48.00,3.20,49.60,5.70);
  nwr["man_made"="winery"](48.00,3.20,49.60,5.70);
  nwr["tourism"="wine_cellar"](48.00,3.20,49.60,5.70);
);
out center tags;
`;

function slug(value) {
  return value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function text(value) {
  return typeof value === "string" ? value.trim() : "";
}

function coordinates(element) {
  const latitude = element.lat ?? element.center?.lat;
  const longitude = element.lon ?? element.center?.lon;
  return Number.isFinite(latitude) && Number.isFinite(longitude)
    ? { latitude, longitude }
    : {};
}

function producerType(tags) {
  const value = `${tags.operator || ""} ${tags.description || ""}`.toLowerCase();
  if (value.includes("coopérative") || value.includes("cooperative")) return "COOPERATIVE";
  return "GROWER";
}

function regionFor(latitude, longitude) {
  if (latitude < 48.35) return "Côte des Bar";
  if (longitude < 3.75) return "Vallée de la Marne";
  if (longitude > 4.25 && latitude < 48.85) return "Côte des Blancs";
  return "Montagne de Reims";
}

function initials(name) {
  return name
    .replace(/^Champagne\s+/i, "")
    .split(/[\s&-]+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0].toUpperCase())
    .join("");
}

const response = await fetch(overpassUrl, {
  method: "POST",
  headers: {
    "Content-Type": "application/x-www-form-urlencoded; charset=utf-8",
    "User-Agent": "ChampagneAtlasBackend/0.2 (open-data sync)"
  },
  body: new URLSearchParams({ data: query })
});

if (!response.ok) {
  throw new Error(`Overpass returned ${response.status}: ${await response.text()}`);
}

const payload = await response.json();
const records = payload.elements
  .map((element) => {
    const tags = element.tags || {};
    const name = text(tags.name);
    const { latitude, longitude } = coordinates(element);
    if (!name || latitude == null || longitude == null) return null;

    const city = text(tags["addr:city"]) || text(tags["addr:place"]) || "Champagne";
    const street = [text(tags["addr:housenumber"]), text(tags["addr:street"])]
      .filter(Boolean)
      .join(" ");
    const address = [street, text(tags["addr:postcode"]), city].filter(Boolean).join(", ");
    const osmType = element.type === "node" ? "node" : element.type === "way" ? "way" : "relation";
    const sourceUrl = `https://www.openstreetmap.org/${osmType}/${element.id}`;

    return {
      id: `osm-${element.type}-${element.id}`,
      name,
      normalizedName: slug(name.replace(/^Champagne\s+/i, "")),
      type: producerType(tags),
      city,
      address: address || `${name}, ${city}, France`,
      region: regionFor(latitude, longitude),
      description: `${name} is als wijnproducent of champagnehuis opgenomen in OpenStreetMap.`,
      website: text(tags.website) || text(tags["contact:website"]),
      directoryUrl: sourceUrl,
      initials: initials(name),
      accent: "FF55766F",
      latitude,
      longitude,
      sourceIds: ["openstreetmap"],
      sourceUpdatedAt: new Date().toISOString().slice(0, 10)
    };
  })
  .filter(Boolean)
  .filter((record, index, all) =>
    all.findIndex((candidate) =>
      candidate.normalizedName === record.normalizedName &&
      candidate.city.toLowerCase() === record.city.toLowerCase()
    ) === index
  )
  .sort((a, b) => a.name.localeCompare(b.name, "fr"));

const generated = `// Generated by sync-open-data.mjs; do not edit manually.
// OpenStreetMap data © OpenStreetMap contributors, available under ODbL.
export const openDataProducers = ${JSON.stringify(records, null, 2)};
`;

await writeFile(outputPath, generated, "utf8");
console.log(`Wrote ${records.length} OpenStreetMap producers to ${outputPath.pathname}`);
